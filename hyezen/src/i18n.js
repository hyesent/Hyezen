// ═══════════════════════════════════════════════════════════
//  HELPER — get strings with English fallback
// ═══════════════════════════════════════════════════════════
export function getStrings(lang) {
  const target = STRINGS[lang] || STRINGS.en;
  // Proxy-like fallback: missing key → English
  return new Proxy(target, {
    get(obj, prop) {
      if (prop in obj) return obj[prop];
      return STRINGS.en[prop] || '';
    },
  });
}
