export function detectInitialLang() {
  try {
    const stored = localStorage.getItem('hx_ui_lang');
    if (stored && SUPPORTED_LANGS.some(l => l.code === stored)) return stored;
  } catch {}
  try {
    const browser = (navigator.language || 'en').toLowerCase().split('-')[0];
    if (SUPPORTED_LANGS.some(l => l.code === browser)) return browser;
  } catch {}
  return 'en';
}

// Replace {key} in a template string
export function interpolate(template, vars = {}) {
  if (!template) return '';
  return template.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? String(vars[k]) : `{${k}}`));
}

